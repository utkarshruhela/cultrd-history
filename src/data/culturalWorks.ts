// CULTRD HISTORY pilot dataset: a small, hand-curated set of anchor works
// per civilization/tradition, built to validate the CulturalWork/
// CivilizationRegion schema (src/types.ts) before scaling up curation.
//
// Coverage note: the originally-approved draft list named 12 broad
// traditions. A few of those turned out to bundle multiple genuinely
// distinct civilizations under one label in a way that would have forced a
// misleading single map pin (e.g. "Mesoamerica" covering both the Maya and
// the Aztec/Mexica, or "Sub-Saharan Africa" covering four unrelated
// kingdoms an ocean apart). Those were split into their own
// CivilizationRegion entries here -- more entries than the original 12, but
// each pin now actually means something. This is a refinement in service of
// the "balanced representation" decision, not a scope change; flag it back
// if a different split is preferred.
//
// Domain coverage: the first pass below (unchanged) is arts-only (49 works),
// predating the domain/discipline split -- every one of those entries got
// `domain: "arts"` mechanically when the schema generalized. A handful are
// arguably philosophy or STEM by subject even though they're tagged arts
// (e.g. the Analects and I Ching read as philosophy; the Canon of Medicine
// and Records of the Grand Historian read as STEM/history) -- flagged here
// rather than reclassified now, since touching them risks creating outright
// duplicates with the STEM pilot below (Canon of Medicine vs. a new STEM
// medicine entry, say) and philosophy hasn't had its own pass yet. Revisit
// when philosophy is scoped.
//
// The second pass (STEM) follows the same discipline: hand-curated, not
// auto-generated, deliberately balanced across all 17 existing
// civilizations rather than weighted toward the easiest English-language
// sources -- including several (Kingdom of Zimbabwe, Ife, Mali, Aksum,
// classical Java) covered with a single, carefully-chosen, well-attested
// entry rather than stretched to match the others' counts with weaker
// claims. Not yet wired into the UI (that's still a later phase) -- this
// file is the data + schema validation step.
